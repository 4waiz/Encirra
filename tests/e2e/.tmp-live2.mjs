import { BASE_URL, launch, waitForApp } from './lib.mjs';
const browser = await launch();
const page = await (await browser.newContext({ viewport: { width: 1600, height: 900 } })).newPage();
const t0 = Date.now();
await page.goto(`${BASE_URL}?page=scenarios`, { waitUntil: 'domcontentloaded' });
await waitForApp(page);
await page.waitForFunction(() => /Live solver/.test(document.querySelector('[data-testid="sim-status"]')?.textContent ?? ''), null, { timeout: 150000 });
console.log(`live after ${Date.now() - t0} ms`);
const tank = page.locator('label:has-text("Initial tank level") input');
console.log('tank before:', await tank.inputValue());
await tank.fill('30');
console.log('button:', await page.locator('[data-testid="scenario-run"]').innerText());
const t1 = Date.now();
await page.locator('[data-testid="scenario-run"]').click();
await page.waitForSelector('[data-testid="busy"]', { timeout: 5000 }).catch(() => {});
await page.waitForFunction(() => !document.querySelector('[data-testid="busy"]'), null, { timeout: 240000 });
console.log(`recompute took ${Date.now() - t1} ms; page live-twin visible: ${await page.locator('[data-testid="live-twin"]').isVisible()}`);
const err = await page.locator('[role="alert"]').allInnerTexts();
console.log('alerts:', err.join(' | ') || 'none');
await page.locator('[data-testid="pb-play"]').click().catch(() => {});
await page.locator('[data-testid="nav-scenarios"]').click();
await page.waitForTimeout(800);
console.log('tank after (from run.params):', await page.locator('label:has-text("Initial tank level") input').inputValue());
await page.locator('[data-testid="nav-reports"]').click();
await page.waitForTimeout(1200);
await page.screenshot({ path: 'tests/e2e/output/live-mode-reports.png' });
const t2 = await page.locator('[data-testid="report-comparison"]').innerText();
console.log(t2.split('\n').filter((l) => /Lowest tank|Minutes below|Water delivered/.test(l)).join(' / '));
await browser.close();
