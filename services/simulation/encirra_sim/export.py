"""Offline replay export: ``python -m encirra_sim.export --out <dir>``.

Writes the ReplayManifest, NetworkTopology and, for every scenario, the three strategy RunResults
plus the Comparison. Files carry ``provenance.source = "replay"``: they are recorded solver output
(pandapower + EPANET via WNTR) produced by this command, not live telemetry.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

from .config import ENGINE_VERSION
from .engine import compare, default_strategies, resolve_weights, scenario_definition, scenario_ids
from .models import ManifestScenario, ReplayManifest, StrategyRuns
from .network_info import build_topology

NOTE = (
    "Precomputed solver output for offline demos: every frame comes from the pandapower AC power flow and the "
    "EPANET 2.2 extended-period hydraulic simulation (via WNTR) of the synthetic district, generated by "
    "`npm run sim:export`. Replays are recorded simulation results, not live telemetry."
)


def _write(path: Path, data: dict) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    path.write_text(text, encoding="utf-8")
    return len(text.encode("utf-8"))


def export(out: Path, use_cache: bool = False) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    sizes = {}
    t0 = time.perf_counter()
    topo = build_topology()
    sizes["topology.json"] = _write(out / "topology.json", topo.model_dump(by_alias=True, mode="json"))
    entries = []
    for sid in scenario_ids():
        t = time.perf_counter()
        comp, runs = compare(sid, source="replay", use_cache=use_cache)
        rels = {}
        for strategy in default_strategies():
            rel = f"{sid}/{strategy}.json"
            sizes[rel] = _write(out / rel, runs[strategy].model_dump(by_alias=True, mode="json"))
            rels[strategy] = rel
        crel = f"{sid}/comparison.json"
        sizes[crel] = _write(out / crel, comp.model_dump(by_alias=True, mode="json"))
        entries.append(
            ManifestScenario(definition=scenario_definition(sid), runs=StrategyRuns(none=rels["none"], grid_only=rels["grid-only"], encirra=rels["encirra"]), comparison=crel)
        )
        s = {k: runs[k].summary for k in default_strategies()}
        print(
            f"[export] {sid}: " + "; ".join(f"{k}: restored {v.load_restored_pct:.1f}% · hospital min {v.min_critical_pressure_m:.1f} m · {v.outcome}" for k, v in s.items()) + f" ({time.perf_counter() - t:.1f}s)",
            flush=True,
        )
    manifest = ReplayManifest(
        generated_at=datetime.now(timezone.utc).isoformat(timespec="seconds"),
        engine_version=ENGINE_VERSION,
        note=NOTE,
        topology="topology.json",
        scenarios=entries,
        default_scenario="feeder-fault",
        default_strategy="encirra",
        weights=resolve_weights(None),
    )
    sizes["manifest.json"] = _write(out / "manifest.json", manifest.model_dump(by_alias=True, mode="json"))
    total = sum(sizes.values())
    print(f"[export] wrote {len(sizes)} files, {total / 1e6:.2f} MB in {time.perf_counter() - t0:.1f}s → {out}", flush=True)
    return sizes


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Export precomputed Encirra replay files")
    ap.add_argument("--out", required=True, help="output directory (e.g. apps/web/public/replay)")
    ap.add_argument("--use-cache", action="store_true", help="reuse cached runs from services/simulation/.cache")
    args = ap.parse_args(argv)
    export(Path(args.out).resolve(), use_cache=args.use_cache)
    return 0


if __name__ == "__main__":
    sys.exit(main())
